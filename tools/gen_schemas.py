"""Generate JSON Schema and TypeScript types from ``sd_schemas`` (``just gen``).

1. Export list: every class in ``sd_schemas.__all__`` that is a pydantic model or an enum.
2. One JSON Schema file with every export under ``$defs``, in validation mode.
3. One ``json2ts`` run turns it into one TypeScript file, so shared types exist once.

The output is byte-identical on every run; ``just gen-check`` relies on that.
OpenAPI snapshots are added here when the ground station's API exists.
"""

from __future__ import annotations

import enum
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any

from pydantic import BaseModel, TypeAdapter
from pydantic.json_schema import models_json_schema

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_FILE = ROOT / "software/common/schemas/generated/sd_schemas.schema.json"
TS_PACKAGE = ROOT / "software/common/ts-schemas"
TS_FILE = TS_PACKAGE / "src/generated/sd_schemas.ts"
BANNER = "// GENERATED by tools/gen_schemas.py. Do not edit."
REF_TEMPLATE = "#/$defs/{model}"


def exported_types() -> list[type]:
    import sd_schemas

    out: list[type] = []
    for name in sorted(sd_schemas.__all__):
        obj = getattr(sd_schemas, name)
        if isinstance(obj, type) and issubclass(obj, BaseModel | enum.Enum):
            out.append(obj)
    return out


def _tidy(node: Any, *, top: bool) -> Any:
    """Shape the schema so json2ts names only real types.

    Drops the per-field ``title`` pydantic adds, and a ``default`` next to a ``$ref``
    (json2ts would otherwise emit a second copy of the referenced type).
    """
    if isinstance(node, dict):
        has_ref = "$ref" in node
        return {
            k: _tidy(v, top=False)
            for k, v in node.items()
            if not (k == "title" and not top and isinstance(v, str))
            and not (k == "default" and has_ref)
        }
    if isinstance(node, list):
        return [_tidy(v, top=False) for v in node]
    return node


def build_schema() -> dict[str, Any]:
    types = exported_types()
    models = [t for t in types if issubclass(t, BaseModel)]
    enums = [t for t in types if issubclass(t, enum.Enum)]
    _, schema = models_json_schema(
        [(m, "validation") for m in models], ref_template=REF_TEMPLATE, title="SdSchemas"
    )
    defs: dict[str, Any] = schema.setdefault("$defs", {})
    for e in enums:
        if e.__name__ not in defs:
            defs[e.__name__] = TypeAdapter(e).json_schema(ref_template=REF_TEMPLATE)
    schema["$defs"] = {name: _tidy(body, top=True) for name, body in sorted(defs.items())}
    return schema


def dump(schema: dict[str, Any]) -> str:
    return json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def run_json2ts() -> None:
    pnpm = shutil.which("pnpm")
    if pnpm is None:
        sys.exit("gen_schemas: pnpm saknas. Kör bash tools/bootstrap.sh.")
    TS_FILE.parent.mkdir(parents=True, exist_ok=True)
    cmd = [
        pnpm,
        "--silent",
        "--filter",
        "@searchdrone/schemas",
        "exec",
        "json2ts",
        "-i",
        os.path.relpath(SCHEMA_FILE, TS_PACKAGE),
        "-o",
        os.path.relpath(TS_FILE, TS_PACKAGE),
        "--unreachableDefinitions",
        "--no-additionalProperties",
        "--unknownAny",
        "--bannerComment",
        BANNER,
    ]
    subprocess.run(cmd, cwd=ROOT, check=True)  # noqa: S603 - fixed argument list


def main() -> int:
    write_text(SCHEMA_FILE, dump(build_schema()))
    run_json2ts()
    print(f"skrev {SCHEMA_FILE.relative_to(ROOT)} och {TS_FILE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
