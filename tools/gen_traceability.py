"""Generate the traceability file from the local acceptance id file (local only).

The acceptance ids belong to the planning and never enter this repository: the id file
(TOML, one table per id with ``typ``, ``dod_ref``, ``sc`` and ``tests``) and the generated
traceability file (YAML) live in the gitignored planning folder. This script is generic:
it holds no ids, it only reads, checks and writes.

    uv run tools/gen_traceability.py [--ids FILE] [--out FILE]

``--ids`` defaults to ``$SD_ACCEPT_IDS``, else ``docs/spec/grunden-v1/accept-ids.toml``;
``--out`` to ``traceability.yaml`` next to it. A missing id file exits 2 with a clear
message; a malformed one exits 1.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import tomllib
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

REPO = Path(__file__).resolve().parent.parent
DEFAULT_IDS = Path("docs/spec/grunden-v1/accept-ids.toml")
TYPES = ("A", "M", "A + M")
SC_PATTERN = re.compile(r"^SC[0-9]{2}$")
# A test (``file.py::test`` or ``file.py::test[case]``) or a whole test file.
NODE_PATTERN = re.compile(r"^[\w/.-]+\.py(::\w+(\[[^\]]+\])?)?$")
MISSING_EXIT = 2


class IdFileError(ValueError):
    """The id file cannot be used."""


@dataclass(frozen=True)
class Entry:
    id: str
    typ: str
    dod_ref: str
    sc: list[str] = field(default_factory=list[str])
    tests: list[str] = field(default_factory=list[str])
    planned: str | None = None  # the ticket that adds the test, while it is not built


def ids_path(arg: str | None) -> Path:
    raw = arg or os.environ.get("SD_ACCEPT_IDS") or str(DEFAULT_IDS)
    path = Path(raw)
    return path if path.is_absolute() else REPO / path


def load(path: Path) -> list[Entry]:
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as exc:
        raise IdFileError(f"{path.name}: {exc}") from exc
    entries = []
    for key, raw in data.items():
        if not isinstance(raw, dict):
            raise IdFileError(f"{key}: ska vara en tabell")
        entries.append(_entry(key, raw))
    return entries


def _entry(key: str, raw: dict[str, Any]) -> Entry:
    unknown = set(raw) - {"typ", "dod_ref", "sc", "tests", "planned"}
    if unknown:
        raise IdFileError(f"{key}: okända nycklar {sorted(unknown)}")
    typ = raw.get("typ")
    if typ not in TYPES:
        raise IdFileError(f"{key}: typ ska vara en av {TYPES}, inte {typ!r}")
    sc = list(raw.get("sc", []))
    bad_sc = [s for s in sc if not SC_PATTERN.match(str(s))]
    if bad_sc:
        raise IdFileError(f"{key}: ogiltiga scenarier {bad_sc}")
    tests = list(raw.get("tests", []))
    bad_tests = [t for t in tests if not NODE_PATTERN.match(str(t))]
    if bad_tests:
        raise IdFileError(f"{key}: ogiltiga testnoder {bad_tests}")
    planned = raw.get("planned")
    return Entry(key, str(typ), str(raw.get("dod_ref", "")), sc, tests, planned)


def problems(entries: list[Entry], scenarios: range = range(0, 19)) -> list[str]:
    """Every automatic id has a test (or names the ticket that adds it), and every
    scenario in ``scenarios`` (default SC00-SC18) is traced at least once."""
    out = []
    for e in entries:
        if "A" in e.typ and not e.tests and not e.planned:
            out.append(f"{e.id}: automatisk rad utan test")
    traced = {s for e in entries for s in e.sc}
    for n in scenarios:
        name = f"SC{n:02d}"
        if name not in traced:
            out.append(f"{name}: inget id pekar på scenariot")
    return out


def to_yaml(entries: list[Entry]) -> str:
    rows = [
        {
            "id": e.id,
            "typ": e.typ,
            "dod_ref": e.dod_ref,
            "sc": e.sc,
            "tests": e.tests,
            **({"planned": e.planned} if e.planned else {}),
        }
        for e in entries
    ]
    head = "# Generated by tools/gen_traceability.py from the local id file. Do not edit.\n"
    return head + yaml.safe_dump({"entries": rows}, sort_keys=False, allow_unicode=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the traceability file.")
    parser.add_argument("--ids")
    parser.add_argument("--out")
    args = parser.parse_args(argv)
    path = ids_path(args.ids)
    if not path.is_file():
        print(
            f"ID-filen {path} saknas. Den finns bara i planeringsmappen (gitignorerad); "
            "sätt SD_ACCEPT_IDS eller --ids."
        )
        return MISSING_EXIT
    try:
        entries = load(path)
    except IdFileError as exc:
        print(f"Fel i ID-filen: {exc}")
        return 1
    found = problems(entries)
    for line in found:
        print(line)
    out = Path(args.out) if args.out else path.with_name("traceability.yaml")
    out.write_text(to_yaml(entries), encoding="utf-8")
    planned = sum(1 for e in entries if e.planned and not e.tests)
    print(f"{len(entries)} id:n, {planned} väntar på sin ticket; skrev {out.name}.")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
