"""Generate the simulator's sd_fpv7 from the fpv7 CAD model (hardware/cad/fpv7).

    just sim-model-fpv7            # write
    just sim-model-fpv7 --check    # compare (CI job hw-cad)

writes ``simulation/gazebo/models/sd_fpv7/``:

- ``cad.json``: mass, centre of gravity and inertia matrix (about the centre of gravity,
  x forward, y left, z up, SI units) from ``checks.mass_properties``, and where the rotors,
  legs, flight controller and camera sit. ``sd_sim.world`` builds the Gazebo model from it
  and ``sd_sim.fpv7`` the builtin-physics frame file, so neither has a hand-written mass;
- ``meshes/<group>.obj`` (+ ``.mtl``): the drone without propellers and screws, one file
  per CAD colour group (frame, motor, battery, ...) in that group's colour, in millimetres
  in the CAD axes (z = 0 under the bottom plate);
- ``meshes/prop_cw.obj`` and ``meshes/prop_ccw.obj``: one three-blade propeller each,
  around its own axis, for the spinning rotor links.

``--check`` builds the same files in a temporary folder and fails when they differ from
the committed ones (numbers in ``cad.json`` to 1e-6, meshes byte for byte), so CAD and
simulator cannot drift apart (CI job ``hw-cad``).
"""

from __future__ import annotations

import argparse
import json
import math
import sys
import tempfile
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parent.parent
CAD = REPO / "hardware" / "cad" / "fpv7"
OUT = REPO / "simulation" / "gazebo" / "models" / "sd_fpv7"
sys.path.insert(0, str(CAD))

# The CAD folder is not a package, and pyright runs without the cad group (cadquery).
import assembly  # noqa: E402  # pyright: ignore[reportMissingImports]
import checks  # noqa: E402  # pyright: ignore[reportMissingImports]
import numpy as np  # noqa: E402
import parts  # noqa: E402  # pyright: ignore[reportMissingImports]

from sd_sim.terrain import Material, Mesh, write_obj  # noqa: E402

MM = 1e-3
# Coarse tessellation (mm, radians): the meshes only have to look like the drone, and
# each file must stay under the repository's 1 MB limit (the plates' screw holes take
# most of the frame's triangles).
BODY_TESSELLATION = (0.8, 0.8)
COARSE_TESSELLATION = {"frame": (2.0, 1.5), "cable": (1.0, 1.2)}
PROP_TESSELLATION = (1.5, 1.0)
# Left out of the body mesh: screws are too small to see, and the propeller discs are the
# checks' swept volumes (the rotor links carry the blades).
SKIP_GROUPS = ("fastener", "prop")
JSON_TOLERANCE = 1e-6


def _centre(part: assembly.Part) -> list[float]:
    box = part.solid.BoundingBox()
    return [box.center.x, box.center.y, box.center.z]


def _m(values: list[float], digits: int = 6) -> list[float]:
    return [round(v * MM, digits) for v in values]


def _mesh(solids: list[tuple[str, Any]], tessellation: tuple[float, float]) -> Mesh:
    mesh = Mesh()
    for material, solid in solids:
        verts, tris = solid.tessellate(*COARSE_TESSELLATION.get(material, tessellation))
        if not tris:
            continue
        points = np.asarray([(v.x, v.y, v.z) for v in verts], dtype=np.float64)
        mesh.add(material, points, np.asarray(tris, dtype=np.int64))
    return mesh


def _materials() -> list[Material]:
    return [Material(name, rgb) for name, rgb in assembly.COLORS.items()]


def body_groups(drone: assembly.Drone) -> list[str]:
    return sorted({pt.group for pt in drone.parts} - set(SKIP_GROUPS))


def describe(p: dict[str, Any], drone: assembly.Drone) -> dict[str, Any]:
    by_name = {pt.name: pt for pt in drone.parts}
    mp = checks.mass_properties(drone)
    pr = p["prop"]
    rotors = []
    for i, cw in enumerate(assembly.CLOCKWISE, start=1):
        box = by_name[f"prop_{i}"].solid.BoundingBox()
        rotors.append(
            {
                "name": f"motor_{i}",
                # The disc's axis and its underside: the blades' own origin (parts.prop_blades).
                "position_m": _m([box.center.x, box.center.y, box.zmin]),
                "clockwise": cw,
            }
        )
    legs = []
    for i in range(1, 5):
        box = by_name[f"leg_{i}"].solid.BoundingBox()
        legs.append(
            {
                "position_m": _m([box.center.x, box.center.y, box.center.z]),
                "size_m": _m([box.xlen, box.ylen, box.zlen]),
            }
        )
    body = [by_name[n].solid.BoundingBox() for n in ("bottom_plate", "top_plate", "battery")]
    lo = [min(b.xmin for b in body), min(b.ymin for b in body), min(b.zmin for b in body)]
    hi = [max(b.xmax for b in body), max(b.ymax for b in body), max(b.zmax for b in body)]
    return {
        "source": "hardware/cad/fpv7 (generated by tools/sim_model_from_cad.py; do not edit)",
        "mass_kg": round(mp["mass_g"] / 1000, 6),
        "cog_m": _m(mp["cog_mm"]),
        "inertia_kg_m2": [[round(v, 9) for v in row] for row in mp["inertia_kg_m2"]],
        "rotors": rotors,
        "prop": {
            "diameter_m": round(pr["diameter_in"] * 0.0254, 6),
            "pitch_in": pr["pitch_in"],
            "blades": pr["blades"],
            "mass_kg": round(pr["mass"] / 1000, 6),
        },
        # The lowest point of the legs: the CAD origin stands this high above the ground.
        "stand_m": round(-min(leg["position_m"][2] - leg["size_m"][2] / 2 for leg in legs), 6),
        "legs": legs,
        "body_box_m": {
            "centre": _m([(a + b) / 2 for a, b in zip(lo, hi, strict=True)]),
            "size": _m([b - a for a, b in zip(lo, hi, strict=True)]),
        },
        "imu_m": _m(_centre(by_name["flight_controller"])),
        "camera_m": _m(_centre(by_name["camera"])),
        "camera_mass_kg": round(by_name["camera"].mass_g / 1000, 6),
        "camera_hfov_deg": p["camera"]["hfov_deg"],
        "meshes": {
            "body": [f"meshes/{group}.obj" for group in body_groups(drone)],
            "prop_cw": "meshes/prop_cw.obj",
            "prop_ccw": "meshes/prop_ccw.obj",
            "scale": MM,
        },
    }


def generate(out: Path) -> None:
    p = assembly.load_params()
    drone = assembly.build(p)
    meshes = out / "meshes"
    meshes.mkdir(parents=True, exist_ok=True)
    text = json.dumps(describe(p, drone), indent=1) + "\n"
    (out / "cad.json").write_text(text, encoding="utf-8")
    for group in body_groups(drone):
        solids = [(group, pt.solid) for pt in drone.parts if pt.group == group]
        write_obj(meshes, group, _mesh(solids, BODY_TESSELLATION), _materials())
    for stem, cw in (("prop_cw", True), ("prop_ccw", False)):
        blades = [("prop", parts.prop_blades(p["prop"], cw))]
        write_obj(meshes, stem, _mesh(blades, PROP_TESSELLATION), _materials())
    # One newline at the end, as the repository's end-of-file hook wants it.
    for path in meshes.glob("*.mtl"):
        path.write_text(path.read_text(encoding="utf-8").rstrip("\n") + "\n", encoding="utf-8")


def _close(a: Any, b: Any) -> bool:
    if isinstance(a, dict) and isinstance(b, dict):
        return a.keys() == b.keys() and all(_close(a[k], b[k]) for k in a)
    if isinstance(a, list) and isinstance(b, list):
        return len(a) == len(b) and all(_close(x, y) for x, y in zip(a, b, strict=True))
    if isinstance(a, float | int) and isinstance(b, float | int) and not isinstance(a, bool):
        return math.isclose(a, b, rel_tol=JSON_TOLERANCE, abs_tol=JSON_TOLERANCE * 1e-3)
    return a == b


def differences(fresh: Path, committed: Path) -> list[str]:
    names = {p.relative_to(fresh) for p in fresh.rglob("*") if p.is_file()}
    have = {p.relative_to(committed) for p in committed.rglob("*") if p.is_file()}
    have = {p for p in have if p.parts[0] in ("meshes",) or p.name == "cad.json"}
    out = [f"saknas: {p}" for p in sorted(names - have)]
    out += [f"finns inte i CAD-modellen: {p}" for p in sorted(have - names)]
    for rel in sorted(names & have):
        a, b = (fresh / rel).read_bytes(), (committed / rel).read_bytes()
        same = _close(json.loads(a), json.loads(b)) if rel.suffix == ".json" else a == b
        if not same:
            out.append(f"skiljer sig från CAD-modellen: {rel}")
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="compare, do not write")
    args = parser.parse_args(argv)
    if not args.check:
        generate(OUT)
        print(f"Skrev {OUT.relative_to(REPO)}")
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        generate(Path(tmp))
        found = differences(Path(tmp), OUT)
    for line in found:
        print(line)
    if found:
        print("Kör tools/sim_model_from_cad.py och checka in resultatet.")
        return 1
    print("sd_fpv7 stämmer med CAD-modellen.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
