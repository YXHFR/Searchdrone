def _append_only_triggers() -> str:
    lines = []
    for t in APPEND_ONLY:
        lines.append(
            f"CREATE TRIGGER {t}_no_update_delete BEFORE UPDATE OR DELETE ON {t} "
            "FOR EACH ROW EXECUTE FUNCTION sd_forbid_change();"
        )
        lines.append(
            f"CREATE TRIGGER {t}_no_truncate BEFORE TRUNCATE ON {t} "
            "FOR EACH STATEMENT EXECUTE FUNCTION sd_forbid_change();"
        )
    return "\n".join(lines)


def _run_script(sql: str) -> None:
    """Run a multi-statement SQL script inside the migration's transaction.

    SQLAlchemy's asyncpg dialect prepares every statement, and a prepared statement
    holds one command only, so the script goes straight to the asyncpg connection
    (simple query protocol). No bind parameters are involved.
    """
    bind = op.get_bind()
    # SQLAlchemy's asyncpg adapter sends BEGIN lazily, on its first statement. Run one
    # through it so the raw script below is inside that transaction (and rolls back with it).
    bind.exec_driver_sql("SELECT 1")
    driver = bind.connection.driver_connection
    if driver is None:
        raise RuntimeError("no database connection")
    if not driver.is_in_transaction():
        raise RuntimeError("migration script must run inside a transaction")
    await_only(driver.execute(sql))


def upgrade() -> None:
    _run_script(REQUIRE_APP_ROLE)
    _run_script(SCHEMA)
    _run_script(GUARD_FUNCTIONS)
    _run_script(_append_only_triggers())
    _run_script(GRANTS)


def downgrade() -> None:
    # Dropping a table drops its triggers, indexes and grants. PostGIS stays.
    # Table names come from the fixed TABLES tuple, never from input.
    _run_script(
        "\n".join(
            [
                "REVOKE SELECT ON alembic_version FROM sd_app;",
                "REVOKE USAGE ON SCHEMA public FROM sd_app;",
                "ALTER TABLE missions DROP CONSTRAINT missions_active_charter_fk;",
                *(f"DROP TABLE {t};" for t in TABLES),
                "DROP FUNCTION sd_charter_body_frozen();",
                "DROP FUNCTION sd_forbid_change();",
            ]
        )
    )
